def simple_compare(query, subject):
    """Compares two sequences using Levenshtein distance."""
    if not query or not subject: return 'no_seq', 'N/A'
    dist = jellyfish.levenshtein_distance(query, subject)
    if dist == 0: return 'mature_identical', 'Identical mature'
    if dist <= 2: return 'mature_similar', 'Similar mature'
    return 'not_similar', 'Not similar'

